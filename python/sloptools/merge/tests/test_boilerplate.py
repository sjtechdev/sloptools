from __future__ import annotations

import ast
import textwrap

import pytest

from sloptools.merge import boilerplate


def _reason(src: str, in_class: bool = True) -> str | None:
    fn = ast.parse(textwrap.dedent(src)).body[0]
    return boilerplate.reason(fn, in_class)


@pytest.mark.parametrize("src,expected", [
    ("""
     @abc.abstractmethod
     def run(self, x):
         y = x + 1
         return y
     """, "abstract"),
    ('''
     def run(self):
         """Subclasses do this."""
     ''', "stub"),
    ("""
     def run(self):
         raise NotImplementedError("subclass")
     """, "stub"),
    ("""
     def run(self, a, *args, **kw):
         return self._impl.run(a, *args, **kw)
     """, "delegation"),
    ("""
     @property
     def name(self):
         return self._name
     """, "accessor"),
    ("""
     @name.setter
     def name(self, value):
         self._name = value
     """, "accessor"),
    ("""
     def __init__(self, a, b: int = 0, *, c=None):
         super().__init__(a)
         self.a = a
         self.b: int = b
         self.items = []
         object.__setattr__(self, "c", c)
     """, "init-assignments"),
    ("""
     def __eq__(self, other):
         if not isinstance(other, (Point, Vector)):
             return NotImplemented
         return (self.x, self.y) == (other.x, other.y)
     """, "attribute-dunder"),
    ("""
     def __repr__(self):
         return f"{type(self).__name__}({self.x!r})"
     """, "attribute-dunder"),
])
def test_boilerplate_is_recognised(src, expected):
    assert _reason(src) == expected


@pytest.mark.parametrize("src", [
    """
    def __init__(self, path):
        self.path = path
        self.data = json.load(open(path))
    """,
    """
    def __eq__(self, other):
        return normalise(self.x) == normalise(other.x)
    """,
    """
    @property
    def total(self):
        return sum(i.price for i in self.items)
    """,
    """
    def run(self, x):
        return self._impl.run(x + 1)
    """,
    """
    def run(self):
        raise ValueError("bad")
    """,
])
def test_real_logic_is_not_boilerplate(src):
    assert _reason(src) is None


@pytest.mark.parametrize("rel,src,expected", [
    ("api/messages_pb2.py", "x = 1\n", True),
    ("api/messages_pb2_grpc.py", "x = 1\n", True),
    ("m.py", "# Generated by Django 4.2 on 2024-01-01\nfrom django.db import migrations\n", True),
    ("m.py", "# -*- coding: utf-8 -*-\n# Automatically generated by gen.py.\n# DO NOT EDIT.\nX = 1\n", True),
    ("m.py", 'revision = "abc"\ndown_revision = "def"\n', True),
    # a docstring mentioning "do not edit" is not a generated-file header
    ("m.py", '"""Do not edit the MODULES dict by hand."""\nMODULES = {}\n', False),
    ("m.py", "import os\n# generated by hand\n", False),
])
def test_generated_files(rel, src, expected):
    assert boilerplate.generated_file(rel, src, ast.parse(src)) is expected
