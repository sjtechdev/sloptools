"""Code that is duplicated on purpose, or by a tool, and isn't worth reporting.

A function matched here is not a unit: it is never grouped. Its statements
still count inside a larger function that contains it. A generated file is
skipped entirely.
"""

from __future__ import annotations

import ast
import re

_GENERATED_NAMES = re.compile(r"_pb2(_grpc)?\.py$")
_GENERATED_HEADER = re.compile(r"\b(auto-?generated|automatically generated|generated by|do not edit)\b", re.I)
_HEADER_LINES = 10

# dunders usually written as a list of attributes: hand-merging them buys nothing
_ATTRIBUTE_DUNDERS = {"__repr__", "__eq__", "__ne__", "__hash__"}
_PLUMBING_NAMES = {"isinstance", "type", "hash", "repr", "str", "tuple", "id", "getattr", "NotImplemented",
                   "super", "object", "True", "False", "None"}


def generated_file(rel: str, src: str, tree: ast.Module) -> bool:
    """Protobuf output, a file whose leading comments say it's generated,
    or an Alembic migration (module-level `revision` and `down_revision`)."""
    if _GENERATED_NAMES.search(rel):
        return True
    for line in src.splitlines()[:_HEADER_LINES]:
        line = line.strip()
        if line and not line.startswith("#"):
            break
        if _GENERATED_HEADER.search(line):
            return True
    assigned = {t.id for n in tree.body if isinstance(n, ast.Assign) for t in n.targets if isinstance(t, ast.Name)}
    return {"revision", "down_revision"} <= assigned


def _body(fn: ast.AST) -> list:
    body = [s for s in fn.body if not isinstance(s, ast.Pass)]
    if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) \
            and isinstance(body[0].value.value, str):
        body = body[1:]
    return body


def _decorators(fn: ast.AST) -> set[str]:
    out = set()
    for d in fn.decorator_list:
        d = d.func if isinstance(d, ast.Call) else d
        if isinstance(d, ast.Attribute):
            out.add(d.attr)
        elif isinstance(d, ast.Name):
            out.add(d.id)
    return out


def _params(fn: ast.AST) -> set[str]:
    a = fn.args
    names = [x.arg for x in a.posonlyargs + a.args + a.kwonlyargs]
    names += [x.arg for x in (a.vararg, a.kwarg) if x]
    return set(names)


def _self_attr(n: ast.AST, self_name: str | None) -> bool:
    return isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name) and n.value.id == self_name


def _plain_value(n: ast.AST | None, params: set[str]) -> bool:
    """A parameter, a constant, or an empty container: nothing computed."""
    if isinstance(n, ast.Name):
        return n.id in params or n.id in _PLUMBING_NAMES
    if isinstance(n, ast.Constant):
        return True
    if isinstance(n, (ast.List, ast.Tuple, ast.Set)) and not n.elts:
        return True
    if isinstance(n, ast.Dict) and not n.keys:
        return True
    return False


def _stores_parameter(st: ast.stmt, self_name: str | None, params: set[str]) -> bool:
    """`self.x = x`, `self.x: T = x`, or `object.__setattr__(self, "x", x)`."""
    if isinstance(st, ast.Assign):
        return all(_self_attr(t, self_name) for t in st.targets) and _plain_value(st.value, params)
    if isinstance(st, ast.AnnAssign):
        return _self_attr(st.target, self_name) and (st.value is None or _plain_value(st.value, params))
    if isinstance(st, ast.Expr) and isinstance(st.value, ast.Call):
        c = st.value
        f = c.func
        if isinstance(f, ast.Attribute) and f.attr == "__setattr__" and isinstance(f.value, ast.Name) \
                and f.value.id == "object" and len(c.args) == 3:
            return isinstance(c.args[0], ast.Name) and c.args[0].id == self_name \
                and isinstance(c.args[1], ast.Constant) and _plain_value(c.args[2], params)
        # super().__init__(...) passing parameters through
        if isinstance(f, ast.Attribute) and f.attr == "__init__" and isinstance(f.value, ast.Call) \
                and isinstance(f.value.func, ast.Name) and f.value.func.id == "super":
            return all(_plain_value(a.value if isinstance(a, ast.Starred) else a, params) for a in c.args) \
                and all(_plain_value(k.value, params) for k in c.keywords)
    return False


def _forwarding_call(n: ast.AST, params: set[str]) -> bool:
    """A call whose arguments are all parameters, passed straight through."""
    if not isinstance(n, ast.Call):
        return False
    args = [a.value if isinstance(a, ast.Starred) else a for a in n.args] + [k.value for k in n.keywords]
    return all(isinstance(a, ast.Name) and a.id in params for a in args)


def _only_attributes(fn: ast.AST, params: set[str]) -> bool:
    """Every name used is a parameter, plumbing (isinstance, hash, ...), or
    a class named in an isinstance check; no loops or assignments."""
    allowed = params | _PLUMBING_NAMES
    for n in ast.walk(fn):
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id == "isinstance" and len(n.args) == 2:
            classes = n.args[1].elts if isinstance(n.args[1], ast.Tuple) else [n.args[1]]
            allowed |= {c.id for c in classes if isinstance(c, ast.Name)}
    for st in _body(fn):
        for n in ast.walk(st):
            if isinstance(n, (ast.For, ast.While, ast.Assign, ast.AugAssign, ast.AnnAssign, ast.With, ast.Try)):
                return False
            if isinstance(n, ast.Name) and n.id not in allowed:
                return False
    return True


def reason(fn: ast.FunctionDef | ast.AsyncFunctionDef, in_class: bool) -> str | None:
    """Why `fn` is boilerplate, or None if it isn't."""
    body = _body(fn)
    params = _params(fn)
    decorators = _decorators(fn)
    self_name = (fn.args.posonlyargs + fn.args.args)[0].arg if in_class and (fn.args.posonlyargs + fn.args.args) else None

    if "abstractmethod" in decorators:
        return "abstract"
    if not body or all(isinstance(s, ast.Expr) and isinstance(s.value, ast.Constant) for s in body):
        return "stub"
    if len(body) == 1 and isinstance(body[0], ast.Raise):
        exc = body[0].exc
        exc = exc.func if isinstance(exc, ast.Call) else exc
        if isinstance(exc, ast.Name) and exc.id == "NotImplementedError":
            return "stub"
    if len(body) == 1 and isinstance(body[0], (ast.Return, ast.Expr)) and _forwarding_call(body[0].value, params):
        return "delegation"
    if in_class and decorators & {"property", "setter", "getter", "deleter", "cached_property"} and len(body) == 1:
        st = body[0]
        if isinstance(st, ast.Return) and _self_attr(st.value, self_name):
            return "accessor"
        if isinstance(st, ast.Assign) and all(_self_attr(t, self_name) for t in st.targets) \
                and _plain_value(st.value, params):
            return "accessor"
    if in_class and fn.name == "__init__" and all(_stores_parameter(s, self_name, params) for s in body):
        return "init-assignments"
    if in_class and fn.name in _ATTRIBUTE_DUNDERS and len(body) <= 4 and _only_attributes(fn, params):
        return "attribute-dunder"
    return None
